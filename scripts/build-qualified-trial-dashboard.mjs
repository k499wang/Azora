import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = resolve(root, 'supabase/functions/send-qualified-trials');
const sourceFiles = ['qualifiedTrial.ts', 'worker.ts', 'index.ts'];
const destinations = [
  resolve(root, 'supabase/send-qualified-trials.txt'),
  resolve(root, 'artifacts/qualified-trial-dashboard/index.ts'),
];
const includedFiles = new Set();
const sections = [];

function parse(file, text) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  if (source.parseDiagnostics.length) throw new Error(`Cannot parse ${file}`);
  return source;
}

for (const file of sourceFiles) {
  const path = resolve(sourceDirectory, file);
  const text = await readFile(path, 'utf8');
  const source = parse(file, text);
  const localImports = [];

  function inspect(node) {
    if (ts.isExportDeclaration(node) && node.moduleSpecifier
      || ts.isImportTypeNode(node)
      || ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
      throw new Error(`Unsupported module reference in ${file}; update this dashboard generator explicitly`);
    }
    if (ts.isImportDeclaration(node)) {
      if (!ts.isStringLiteral(node.moduleSpecifier)) throw new Error(`Unsupported import in ${file}`);
      const specifier = node.moduleSpecifier.text;
      if (specifier.startsWith('.')) {
        if (!includedFiles.has(resolve(dirname(path), specifier))) {
          throw new Error(`Local import ${specifier} in ${file} must reference an earlier bundled file`);
        }
        const clause = node.importClause;
        if (!clause || clause.name || !clause.namedBindings || !ts.isNamedImports(clause.namedBindings)
          || clause.namedBindings.elements.some((binding) => binding.propertyName)) {
          throw new Error(`Only direct named local imports are supported in ${file}`);
        }
        localImports.push({ start: node.getStart(source), end: node.getEnd() });
      } else if (file !== 'index.ts' || specifier !== 'https://esm.sh/@supabase/supabase-js@2') {
        throw new Error(`Unexpected external import ${specifier} in ${file}`);
      }
    }
    ts.forEachChild(node, inspect);
  }
  inspect(source);

  let bundled = text;
  for (const { start, end } of localImports.reverse()) bundled = bundled.slice(0, start) + bundled.slice(end);
  sections.push(`// Source: supabase/functions/send-qualified-trials/${file}\n${bundled.trim()}`);
  includedFiles.add(path);
}

const output = '// Generated by scripts/build-qualified-trial-dashboard.mjs. Edit the source modules, then regenerate.\n\n'
  + sections.join('\n\n') + '\n';
const bundledSource = parse('dashboard/index.ts', output);
for (const node of bundledSource.statements) {
  if (ts.isImportDeclaration(node) && node.moduleSpecifier.text.startsWith('.')) {
    throw new Error('Generated dashboard function still contains a local import');
  }
}
for (const destination of destinations) {
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, output);
  console.log(`Generated ${destination}`);
}
